/* spi_driver_desc_t: what a SPI device driver (e.g. a display panel) fills in; a raw device has none. */
#pragma once

#include "bm_spi.h"   /* bm_err_t + the opaque spi_dev_t */
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* PHP function table; only the pointer is used here, so the engine headers are not pulled in. */
typedef struct _zend_function_entry zend_function_entry;

typedef struct spi_driver_desc {
    const char *name;              /* driver key, e.g. "st77916" */
    const char *php_class;         /* registered class Baremetal\Spi\Driver\<php_class>; extends Device */
    const char *capability;        /* interface FQN this driver implements, or NULL */

    int      default_cs;           /* chip-select pin default (-1 = none) */
    uint32_t default_hz;
    uint8_t  default_mode;         /* SPI mode 0..3 */
    bool     managed_io;           /* true: the driver owns its wire traffic; no raw HAL device is opened */

    size_t   state_size;           /* per-instance state, allocated in the device registry */
    bm_err_t (*init)(spi_dev_t *d);
    void      (*deinit)(spi_dev_t *d);

    const zend_function_entry *methods;
} spi_driver_desc_t;

/* The spi_drivers registry, generated by the build from the packages that register into it
 * (extra.baremetal.register.spi_drivers). NULL-terminated; empty when no driver is installed. */
extern const spi_driver_desc_t *const spi_drivers[];
extern const size_t spi_drivers_count;
